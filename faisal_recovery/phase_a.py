def code_tokens(code):
    return set(code.split("_"))


ALWAYS_META = {"STATED", "REDACTED", "HIDDEN"}


def code_family(code):
    """EXTERNAL · META · CHART for one statement reason code. Pure, rule-based (documented in the report)."""
    if code.startswith(CHART_EXCEPT):
        return "CHART"
    t = code_tokens(code)
    if t & EXT_TOKENS or code in ("NO_SHORT", "NO_GROUPS", "NO_NEWS", "NAME_CHANGE"):
        return "EXTERNAL"
    if t & ALWAYS_META or code in META_TOKENS or (t & META_TOKENS and not t & STRUCTURE_TOKENS):
        return "META"
    return "CHART"


