# ── text references (S20) ───────────────────────────────────────────────────────────────────────────────────────────
_FAM = re.compile(r"\b(IMG_\d{3,5}|(?:TG|X|APP|CH|EDU|WA|NEW)_\d{8}_[A-Za-z0-9_]+|TG_\d{3,6})\b")
_SLASH = re.compile(r"IMG[_-](\d{4})((?:\s*/\s*\d{4})+)")
_RANGE = re.compile(r"IMG[_-](\d{4})\s*(?:-|–|…|\.\.\.|⟶|→)\s*(?:IMG[_-])?(\d{4})(?![\d.])")
_PAREN = re.compile(r"\((\d{4}(?:\s*/\s*\d{4})+)\)")
_EQUIV = re.compile(r"`?(" + _FAM.pattern[2:-2] + r")`?\s*≡\s*`?(" + _FAM.pattern[2:-2] + r")`?")
PAREN_DOCS = ("FAISAL_IMAGES_CATALOG.md", "FAISAL_METHODOLOGY_NOTES.md", "FAISAL_IMAGE_PASS2.md", "FAISAL_IMAGE_PASS3.md",
              "faisal_images/README.md")
TEXT_EXT = (".md", ".tsv", ".json", ".jsonl", ".csv", ".txt", ".py")
FIXTURE_FILES = ("test_bot.py",)


def scan_references(texts, stems, tg_dup_msgs):
    """Rules R1-R6 over every tracked text file. Returns {token: {"where": [...], "rules": [...]}} for tokens that are NOT
    corpus stems, plus the resolution of each. Pure (texts = {relpath: content})."""
    found = collections.defaultdict(lambda: {"where": set(), "rules": set()})

    def hit(tok, f, rule):
        found[tok]["where"].add(f)
        found[tok]["rules"].add(rule)
    equiv = {}
    for f, t in texts.items():
        for m in _FAM.finditer(t):
            hit(m.group(1), f, "R1-token")
        for m in _SLASH.finditer(t):
            for n in re.findall(r"\d{4}", m.group(2)):
                hit("IMG_" + n, f, "R2-slash")
        for m in _RANGE.finditer(t):
            a, b = int(m.group(1)), int(m.group(2))
            if 0 < b - a <= 60:
                for k in range(a, b + 1):
                    hit(f"IMG_{k:04d}", f, "R3-range")
        if f in PAREN_DOCS:
            for m in _PAREN.finditer(t):
                for n in re.findall(r"\d{4}", m.group(1)):
                    if n not in ("2023", "2024", "2025", "2026"):
                        hit("IMG_" + n, f, "R4-paren")
        for m in _EQUIV.finditer(t):
            a, b = m.group(1), m.group(m.lastindex)
            if a not in stems and b in stems:
                equiv.setdefault(a, b)
            elif b not in stems and a in stems:
                equiv.setdefault(b, a)
    if "faisal_levels_table.tsv" in texts:
        for row in csv.DictReader(io.StringIO(texts["faisal_levels_table.tsv"]), delimiter="\t"):
            for tok in (row.get("images") or "").split():
                for x in expand_compound(tok, stems):
                    hit(x, "faisal_levels_table.tsv", "R5-levels")
    if "FAISAL_IMAGE_AUDIT.md" in texts:
        for ln in texts["FAISAL_IMAGE_AUDIT.md"].splitlines():
            m = re.match(r"\|\s*([A-Za-z]+_[^|\s]+)\s*\|", ln)
            if m and m.group(1) != "المعرّف":
                hit(m.group(1), "FAISAL_IMAGE_AUDIT.md", "R6-audit")
    out = {}
    for tok, v in found.items():
        if tok in stems:
            continue
        where = sorted(v["where"])
        if tok.endswith("_") or re.search(r"_NN(_|$)", tok):
            res, why = "EXCLUDED", "template, not a name"
        elif all(w in FIXTURE_FILES for w in where):
            res, why = "EXCLUDED", "test fixture token (only in " + ", ".join(where) + ")"
        elif any(s.startswith(tok + "_") for s in stems):
            res, why = "RESOLVED_BY_NAME", "abbreviation of an existing corpus file name"
        elif (re.fullmatch(r"IMG_\d{3}", tok) or re.fullmatch(r"[A-Z]+_\d{8}_\d", tok)) and \
                any(s.startswith(tok) and len(s) > len(tok) and s[len(tok)].isdigit() for s in stems):
            res, why = "RESOLVED_BY_NAME", "truncated text (too short to be an ID; a prefix of existing corpus IDs)"
        elif re.fullmatch(r"TG_\d+", tok) and int(tok[3:]) in tg_dup_msgs:
            res, why = "TELEGRAM_DUPLICATE_MESSAGE", "name of a received-but-not-saved Telegram message (record in S10)"
        elif tok in equiv:
            res, why = "EQUIVALENT_STORED_UNDER_OTHER_NAME", f"≡ {equiv[tok]} (documented duplicate never saved twice)"
        else:
            res, why = "REFERENCE_ONLY", "named in text; no file in any accessible source"
        out[tok] = {"where": where, "rules": sorted(v["rules"]), "resolution": res, "why": why,
                    "equivalent_to": equiv.get(tok)}
    return out


def expand_compound(tok, stems):
    """Levels-table compound tokens: 'IMG_6004/6005' · 'CH_01/02/03_ELPW' (batch code → dated corpus names) · 'X_….jpg'. Pure."""
    tok = re.sub(r"\.(jpe?g|png|webp)$", "", tok)
    m = re.match(r"^IMG_(\d{4})((?:/\d{4})+)$", tok)
    if m:
        return ["IMG_" + m.group(1)] + ["IMG_" + x for x in m.group(2).split("/") if x]
    m = re.match(r"^(CH|TG|X|WA|APP|EDU)_(\d{2}(?:/\d{2})*)_([A-Za-z].*)$", tok)
    if m:
        out = []
        for n in m.group(2).split("/"):
            c = sorted(s for s in stems if re.match(rf"^{m.group(1)}_2026\d{{4}}_{n}_{re.escape(m.group(3))}$", s))
            out += c if c else [f"{m.group(1)}_UNDATED_{n}_{m.group(3)}"]
        return out
    return [tok]


def tracked_texts():
    import subprocess
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split("\n")
    texts = {}
    for f in files:
        if not f or f.startswith("faisal_recovery/") or not f.endswith(TEXT_EXT):
            continue
        p = _p(f)
        if os.path.getsize(p) > 30_000_000:
            continue
        with open(p, encoding="utf-8", errors="ignore") as fh:
            texts[f] = fh.read()
    return texts


