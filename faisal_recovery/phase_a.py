def make_seal(rc, srcs, manifest, records, audit, main_commit, branch_head, timestamp, collector_last, cutoff):
    status = "CLOSED" if (rc["remainder"] == 0 and not rc["duplicate_ids"] and rc["classes"]["UNKNOWN"] == 0
                          and all(a["answer"] in ("YES", "NO") for a in audit)
                          and all(a["answer"] == "YES" for a in audit if a["n"] not in (8, 9))
                          and all(a["answer"] == "NO" for a in audit if a["n"] in (8, 9))) else "BLOCKED"
    c = rc["classes"]
    body = {
        "schema": "phase_a_seal/1", "timestamp": timestamp, "main_commit": main_commit, "branch_head_at_seal": branch_head,
        "v4_commit": V4_COMMIT, "source_manifest_hash": canon_hash(srcs), "corpus_manifest_hash": canon_hash(manifest),
        "records_hash": canon_hash(records), "corpus_before": CORPUS_BEFORE, "corpus_after": CORPUS_BEFORE + c["NEW_TO_CORPUS"],
        "corpus_manifest_count": len(manifest), "total_discovered": rc["total"], "total_recovered": rc["recovered"],
        "new_to_corpus": c["NEW_TO_CORPUS"], "duplicates": c["EXACT_DUPLICATE"], "derivatives": c["INFORMATIVE_DERIVATIVE"],
        "reference_only": c["IMAGE_REFERENCE_ONLY"], "inaccessible": c["INACCESSIBLE_IMAGE"], "missing": c["MISSING_ATTACHMENT"],
        "non_faisal": c["NON_FAISAL"], "unknown": c["UNKNOWN"], "unresolved": rc["remainder"],
        "telegram_drained_at_seal": collector_last, "status": status,
        "evidence_cutoff_utc": cutoff, "prospective_clock_starts_after": cutoff,
    }
    body["seal_id"] = "PHA-" + canon_hash(body)[:16]
    return body


