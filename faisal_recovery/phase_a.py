# ── reconciliation, audit, seal ──────────────────────────────────────────────────────────────────────────────────────
def reconcile(records):
    cls = classify_count(records)
    total = len(records)
    recovered = sum(1 for r in records if r["BYTES_OPENED_THIS_MISSION"].startswith("yes"))
    by_src = collections.defaultdict(collections.Counter)
    for r in records:
        by_src[r["SOURCE_ID"]][r["CORPUS_CLASSIFICATION"]] += 1
    dup_target = collections.Counter(r["DUPLICATE_OF_CLASS"].split(" (")[0] for r in records if r["CORPUS_CLASSIFICATION"] == "EXACT_DUPLICATE")
    remainder = total - sum(cls.values())
    ids = collections.Counter(r["IMAGE_ID"] for r in records)
    return {"total": total, "recovered": recovered, "classes": cls, "remainder": remainder,
            "duplicate_ids": sorted(k for k, v in ids.items() if v > 1), "by_source": {k: dict(v) for k, v in sorted(by_src.items())},
            "exact_duplicate_targets": dict(sorted(dup_target.items()))}


