# ── helpers ──────────────────────────────────────────────────────────────────────────────────────────────────────────
def _p(*a):
    return os.path.join(ROOT, *a)


def _j(rel):
    with open(_p(rel), encoding="utf-8") as f:
        return json.load(f)


def _sha_bytes(b):
    return hashlib.sha256(b).hexdigest()


def _sha_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def canon(obj):
    """Canonical JSON (sorted keys, no whitespace variance) — every hash in the seal is over this form. Pure."""
    return json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def canon_hash(obj):
    return hashlib.sha256(canon(obj).encode("utf-8")).hexdigest()


def sniff(head):
    for sig, kind in MAGIC:
        if head.startswith(sig):
            return kind
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "webp"
    return None


def classify_count(records):
    c = collections.Counter(r["CORPUS_CLASSIFICATION"] for r in records)
    return {k: c.get(k, 0) for k in CLASSES}


def rec(**kw):
    """One inventory record with every A4 field present (empty string when not applicable). Pure."""
    r = {k: "" for k in CSV_FIELDS}
    for k, v in kw.items():
        if k not in r:
            raise KeyError(k)
        r[k] = " · ".join(str(x) for x in v) if isinstance(v, (list, tuple)) else ("" if v is None else str(v))
    if r["CORPUS_CLASSIFICATION"] not in CLASSES:
        raise ValueError(f"bad class {r['CORPUS_CLASSIFICATION']!r} for {r['IMAGE_ID']}")
    return r


def pfmt(d256, p64):
    return f"d256:{d256}|p64:{p64}" if d256 or p64 else ""


# ── corpus baseline ──────────────────────────────────────────────────────────────────────────────────────────────────
def corpus_manifest(inputs):
    """The sealed historical corpus: every file in faisal_images/ (SHA256 recomputed now; perceptual hashes from the
    frozen corpus inventory) + the session attachment (from the recorded measurement). Fails loudly on any mismatch
    between the file on disk and the inventory hash."""
    inv = {r["IMAGE_ID"]: r for r in _j("faisal_method_v41/corpus_audit/MASTER_CORPUS_INVENTORY.json")["rows"]}
    rows = []
    folder = _p("faisal_images")
    for f in sorted(os.listdir(folder)):
        if not f.lower().endswith(IMG_EXT):
            continue
        stem = os.path.splitext(f)[0]
        sha = _sha_file(os.path.join(folder, f))
        r = inv.get(stem)
        if r is None:
            raise SystemExit(f"⛔ corpus file without an inventory row: {f}")
        if r["HASH"] != sha:
            raise SystemExit(f"⛔ corpus file changed since the corpus audit: {f}")
        ph = r.get("PERCEPTUAL_HASH") or {}
        rows.append({"id": stem, "path": f"faisal_images/{f}", "sha256": sha, "dhash256": ph.get("dhash256"),
                     "phash64": ph.get("phash64"), "kind": "file"})
    up = inputs["uploads_current"][0]
    rows.append({"id": "ATTACHMENT_" + up["name"].split("-")[0], "path": "session-attachment:" + up["name"],
                 "sha256": up["sha256"], "dhash256": up["dhash256"], "phash64": up["phash64"], "kind": "attachment"})
    return rows


