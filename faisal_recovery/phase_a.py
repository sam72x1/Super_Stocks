def validate(frozen):
    """Every invariant the seal promises. Returns a list of problems (empty = sound). Pure on its input + the working tree."""
    P = []
    seal, records, manifest, srcs = frozen["seal"], frozen["records"], frozen["manifest"], frozen["sources"]
    rc = reconcile(records)
    if rc["remainder"]:
        P.append(f"unexplained remainder {rc['remainder']}")
    if rc["duplicate_ids"]:
        P.append(f"duplicate record ids {rc['duplicate_ids'][:3]}")
    for r in records:
        if r["CORPUS_CLASSIFICATION"] not in CLASSES:
            P.append(f"bad class {r['IMAGE_ID']}")
        if r["CORPUS_CLASSIFICATION"] == "EXACT_DUPLICATE" and not r["DUPLICATE_OF_CLASS"]:
            P.append(f"duplicate without target class {r['IMAGE_ID']}")
        if r["BYTES_OPENED_THIS_MISSION"] == "no" and r["CORPUS_CLASSIFICATION"] in ("NEW_TO_CORPUS", "INFORMATIVE_DERIVATIVE"):
            P.append(f"content class without bytes {r['IMAGE_ID']}")
    c = rc["classes"]
    exp = {"total_discovered": rc["total"], "total_recovered": rc["recovered"], "new_to_corpus": c["NEW_TO_CORPUS"],
           "duplicates": c["EXACT_DUPLICATE"], "derivatives": c["INFORMATIVE_DERIVATIVE"], "reference_only": c["IMAGE_REFERENCE_ONLY"],
           "inaccessible": c["INACCESSIBLE_IMAGE"], "missing": c["MISSING_ATTACHMENT"], "non_faisal": c["NON_FAISAL"],
           "unknown": c["UNKNOWN"], "unresolved": rc["remainder"], "source_manifest_hash": canon_hash(srcs),
           "corpus_manifest_hash": canon_hash(manifest), "records_hash": canon_hash(records), "v4_commit": V4_COMMIT,
           "corpus_manifest_count": len(manifest)}
    for k, v in exp.items():
        if seal.get(k) != v:
            P.append(f"seal field {k}: sealed {seal.get(k)!r} ≠ recomputed {v!r}")
    body = {k: v for k, v in seal.items() if k != "seal_id"}
    if seal.get("seal_id") != "PHA-" + canon_hash(body)[:16]:
        P.append("seal_id does not match the seal body")
    try:                                                 # the whole seal — status included — is a function of the frozen data
        again = make_seal(rc, srcs, manifest, records, exhaustiveness(rc, srcs, frozen["docrefs"]), seal["main_commit"],
                          seal["branch_head_at_seal"], seal["timestamp"], seal["telegram_drained_at_seal"], seal["evidence_cutoff_utc"])
        if again != seal:
            P.append("seal differs from its recomputation: " + ", ".join(sorted(k for k in set(again) | set(seal)
                                                                                 if again.get(k) != seal.get(k))))
    except KeyError as e:
        P.append(f"seal field missing: {e}")
    if seal.get("evidence_cutoff_utc") != frozen["probe"].get("listed_at_utc") or \
            seal.get("evidence_cutoff_utc") != frozen["inputs"]["transcript_current"]["recheck"]["cutoff_utc"]:
        P.append("evidence cutoff disagrees with the artifact listing or the transcript cutoff")
    if frozen["inputs"]["transcript_current"]["recheck"]["blocks_after_cutoff"] or \
            frozen["collector"]["cutoff_verification"]["updates_of_any_kind"]:
        P.append("evidence after the cutoff was not excluded or the bot queue was not empty at the cutoff")
    for m in manifest:                                   # historical images are immutable for the epoch
        if m["kind"] != "file":
            continue
        p = _p(m["path"])
        if not os.path.exists(p):
            P.append(f"sealed historical image missing: {m['path']}")
        elif _sha_file(p) != m["sha256"]:
            P.append(f"sealed historical image changed: {m['path']}")
    return P


def check():
    frozen = load_frozen()
    P = validate(frozen)
    for name, text in render_all(frozen).items():
        try:
            cur = _read(name)
        except FileNotFoundError:
            P.append(f"missing artifact {name}")
            continue
        if cur != text:
            P.append(f"artifact differs from its frozen data: {name}")
    for p in P:
        print("⛔", p)
    print("✅ PHASE A check: sound" if not P else f"⛔ PHASE A check: {len(P)} problem(s)")
    return 1 if P else 0


def build(timestamp, main_commit, branch_head):
    inputs = json.loads(_read("data/phase_a_inputs.json"))
    probe = json.loads(_read("data/artifact_probe_result.json"))
    collector = inputs["collector"]
    manifest = corpus_manifest(inputs)
    stems = {m["id"] for m in manifest if m["kind"] == "file"}
    texts = tracked_texts()
    tg_dup = {m["msg"] for m in collector["accounted_records"]}
    refs = scan_references(texts, stems, tg_dup)
    rc_counts = collections.Counter(v["resolution"] for v in refs.values())
    docrefs = {"refs": refs, "counts": {
        "files_scanned": len(texts), "tokens": len(refs), "reference_only": rc_counts["REFERENCE_ONLY"],
        "equivalent": rc_counts["EQUIVALENT_STORED_UNDER_OTHER_NAME"], "telegram_dup": rc_counts["TELEGRAM_DUPLICATE_MESSAGE"],
        "resolved_by_name": rc_counts["RESOLVED_BY_NAME"], "excluded": rc_counts["EXCLUDED"]}}
    srcs = sources(inputs, probe, collector, docrefs)
    records = build_records(inputs, probe, collector, manifest, docrefs)
    dec = decision_forensics()
    for k, obj in (("manifest", manifest), ("sources", srcs), ("docrefs", docrefs)):
        _write(FROZEN[k], json.dumps(obj, ensure_ascii=False, indent=0, sort_keys=True) + "\n")
    _write(OUT["inventory"], render_inventory_csv(records))
    _write(OUT["decisions"], render_decisions_csv(dec))
    if _csv_rows(OUT["inventory"]) != records:            # the seal hashes exactly what is published
        raise SystemExit("⛔ inventory CSV does not round-trip")
    rc = reconcile(records)
    audit = exhaustiveness(rc, srcs, docrefs)
    seal = make_seal(rc, srcs, manifest, records, audit, main_commit, branch_head, timestamp, collector["last_run_id"],
                     probe["listed_at_utc"])
    _write(OUT["seal"], json.dumps(seal, ensure_ascii=False, indent=1, sort_keys=True) + "\n")
    frozen = load_frozen()
    for name, text in render_all(frozen).items():
        _write(name, text)
    P = validate(frozen)
    print(json.dumps({"status": seal["status"], "seal_id": seal["seal_id"], "total": rc["total"], "classes": rc["classes"],
                      "recovered": rc["recovered"], "remainder": rc["remainder"], "problems": P}, ensure_ascii=False))
    return 0 if not P else 1


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", nargs="?", default="check", choices=("build", "check"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--timestamp")
    ap.add_argument("--main-commit")
    ap.add_argument("--branch-head")
    a = ap.parse_args(argv)
    if a.check or a.mode == "check":
        return check()
    ts = a.timestamp or dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return build(ts, a.main_commit or "", a.branch_head or "")


if __name__ == "__main__":
    sys.exit(main())
