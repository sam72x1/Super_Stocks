def _write(rel, text):
    p = os.path.join(HERE, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def _read(rel):
    with open(os.path.join(HERE, rel), encoding="utf-8", newline="") as f:
        return f.read()


