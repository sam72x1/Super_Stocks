def _md_table(rows, keys):
    out = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(k, "")).replace("|", "/").replace("\n", " ") for k in keys) + " |")
    return "\n".join(out) + "\n"


