"""Faisal condition atlas — renders SOURCE_CONDITION_ATLAS.md and HISTORICAL_DATA_INVENTORY.md from the data
(`ca_atlas.ATLAS`, `data/inventory.json`, `data/strength_dev.json`). The narrative sections of the other reports are
written by hand from the JSON files they cite.
Run from the repo root:  python3 faisal_engine/readynow/condition_atlas/ca_docs.py   (--check compares)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ca_atlas as A                                                      # noqa: E402

DATA = os.path.join(HERE, "data")
AUTH = {"F": "Faisal", "A": "app screen", "T": "third party", "P": "project rule"}


def _cell(x):
    return str(x).replace("|", "/").replace("\n", " ")


def atlas_md():
    L = ["# Source condition atlas — Faisal's technical conditions", "",
         "Generated by `ca_docs.py` from `ca_atlas.py` (one entry per condition). Quotes are verbatim from the "
         "original image (column «seen»: *viewed 2026-10-11* = opened in this study; *register* = the eye-read "
         "register `fm_forensics/reread/data/reread_records.jsonl`, 772/772 images). Author: **Faisal** = @kisar_ "
         "himself; **app screen** = a third-party tool that applies his method (not his words); **third party** = "
         "an education channel or a follower; **project rule** = the bot's own rule.", "",
         "Classification columns: **kind** pivot · strength · timing · confirmation · invalidation; **strict** "
         "mandatory · likely optional · undecided; **conf** documented · reconstructed from example · hypothetical; "
         "**data** testable · partial · not available. «split» separates what was said from what is inferred or "
         "proposed. «prior» names any earlier measurement against the onset-in-7–10 target.", "",
         "| id | condition | quote (verbatim) | source · author · seen | formula on daily bars ≤ T | tf | kind | strict "
         "| conf | data | said / inferred / proposed | prior |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for a in A.ATLAS:
        L.append("| " + " | ".join(_cell(x) for x in (
            a["id"], f'{a["ar"]} — {a["en"]}', a["quote"], f'{", ".join(a["src"])} · {AUTH[a["author"]]} · {a["seen"]}',
            a["formula"], a["tf"], a["kind"], a["strict"], a["conf"], a["data"], a["split"], a["prior"])) + " |")
    n = len(A.ATLAS)
    cnt = {}
    for a in A.ATLAS:
        for k in ("kind", "data", "author", "conf"):
            cnt.setdefault(k, {}).setdefault(a[k], 0)
            cnt[k][a[k]] += 1
    L += ["", f"**Totals.** {n} conditions · by kind {cnt['kind']} · by data status {cnt['data']} · by author "
          f"{ {AUTH[k]: v for k, v in cnt['author'].items()} } · by confidence {cnt['conf']}.", ""]
    L += ["## Conflicts and readings recorded (not resolved by choice)", "",
          "- **Above or below the averages.** Faisal's checklist says that after RSI < 30 «يتبقى ثبات السعر اعلى من "
          "متوسط 30-50» (X_20260827_checklist_7points), while his other posts and the app say «متوسطات حركه "
          "هبوطيه» / «أسفل EMA20/30/50» (TG_1967, TG_57915) and «تحط طلبك تحت المتوسطات 10٪» (X_20260918_21). "
          "His «حقق متوسط 30/50 يوم» is elapsed time from the split or the high (IMG_0179, TG_1807, TG_58419), "
          "which reconciles part of it. Both readings are kept (B03, B04, B21) and measured separately.",
          "- **RSI band.** 23–27 (TG_2043), 22–27 (IMG_0531), 20–27 (IMG_0177), below 30 (checklist), the tool 33. "
          "The study measures < 30, < 33, the lowest of 10 sessions ≤ 27, and 20–27.",
          "- **Sweep depth.** 5% under the low candle (TG_50584), about 10% (TG_2203, TG_1958), 10–15% (TG_57874), "
          "7–13% (IMG_0297, an unnamed channel adopted by the bot), 15% for individuals' stops (TG_57870). The "
          "study uses 5–15% (B08).",
          "- **Hold length.** 3 (IMG_0151), 3–5 (TG_2066), more than 5 (YMT, checklist #7), 2 (the app chip). "
          "3 and 5 are measured; the app's «stability» chip was shown not to equal any hold count (RN_AUDIT A2).",
          "- **Frame.** Most candle, support and group rules are stated on the 4-hour frame (IMG_0569, TG_1865, "
          "TG_57917, TG_58420). No 4-hour history exists for the population, so every 4-hour rule is a daily proxy "
          "(data «partial»).",
          "- **Third-party material.** The candle tutorial TG_58382 (doji or morning star must be followed by an "
          "engulfing) is an education channel, and the weighted screen TG_58420 is an app; both are recorded with "
          "their author and never counted as Faisal's words.", ""]
    L += ["## What is not computable and why", "",
          "- Float / share count (A09), short available (A10), offering (A12), news (A13): no point-in-time "
          "history for the pivot population (see HISTORICAL_DATA_INVENTORY.md).",
          "- Operator pressure and entry (T03), extended-hours behaviour (T04): intraday and extended bars are not "
          "archived for the population; Polygon ended 2026-09-29.",
          "- Groups (A11): a daily proxy of a 4-hour candle shape only.", ""]
    return "\n".join(L) + "\n"


def inventory_md():
    inv = json.load(open(os.path.join(DATA, "inventory.json"), encoding="utf-8"))
    L = ["# Historical data inventory", "",
         "Generated by `ca_docs.py` from `data/inventory.json`, which `ca_inventory.py` builds by reading each file "
         "(counts are from the files, not from earlier reports). No external download, network call or API was used.",
         "", "| source | path | size / records | period | point-in-time | original or rebuilt | limits |",
         "|---|---|---|---|---|---|---|"]
    for x in inv:
        rec = []
        for k in ("symbols", "daily_rows", "rows", "events", "reverse_events", "filings", "files", "images"):
            if x.get(k) is not None:
                rec.append(f"{k} {x[k]:,}" if isinstance(x[k], int) else f"{k} {x[k]}")
        per = x.get("date_range") or x.get("first_date_range")
        per = f"{per[0]} → {(x.get('last_date_range') or per)[1]}" if per else "—"
        L.append("| " + " | ".join(_cell(v) for v in (x["source"], x["path"], " · ".join(rec) or "—", per,
                                                        x.get("pit", "—"), x.get("original", "—"),
                                                        x.get("limits", "—"))) + " |")
    L += ["", "**Detail kept in the JSON:** the label counts of the pivot rows, the SEC offering-form counts, the "
          "hourly symbols of the Phase 6 bars and the author counts of the image register.", "",
          "## What the inventory decides for the atlas", "",
          "- Daily OHLCV with dated splits exists for the whole pivot population (2024-05-01 → 2026-10-08): every "
          "daily condition can be computed point-in-time.",
          "- **No 4-hour, hourly or extended-hours history** for the population (hourly bars for CRE, DKI, HUBC, "
          "SXTC only): 4-hour rules are daily proxies; operator-entry and pre-market conditions are untestable.",
          "- **No historical float or borrow:** the company cache is overwritten; borrow and pre-session ledgers "
          "start in July–September 2026 and cover the bot's lists only.",
          "- **SEC filings and share counts exist point-in-time for 238 symbols** selected on 2026-10-08 (a biased "
          "subset); used only descriptively.",
          "- The Phase 6 ledger and every log from 2026-10-08 on are prospective and excluded by instruction.", ""]
    return "\n".join(L) + "\n"


def main(check=False):
    out = {"SOURCE_CONDITION_ATLAS.md": atlas_md(), "HISTORICAL_DATA_INVENTORY.md": inventory_md()}
    bad = []
    for name, txt in out.items():
        path = os.path.join(HERE, name)
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != txt:
                bad.append(name)
        else:
            open(path, "w", encoding="utf-8").write(txt)
    return bad


if __name__ == "__main__":
    if "--check" in sys.argv:
        b = main(True)
        print("❌ differs: " + ", ".join(b) if b else "✅ documents match")
        sys.exit(1 if b else 0)
    main()
    print("written")
