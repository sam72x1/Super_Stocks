"""Renders the four historical-4H documents from data/h4_audit.json (called by h4_audit.py; no other input)."""

HEAD = ("> Generated by `h4_audit.py` from `data/h4_audit.json` (rebuild: `python3 faisal_engine/readynow/condition_atlas/"
        "h4_audit.py`; verify: `… --check`). Research only · read-only · no network · nothing fetched · "
        "`faisal_engine/readynow/fwd/` not read. Every number below is computed from the listed local sources.")
W = ("development", "validation", "holdout")


def _ci(c):
    return f"[{c[0]}, {c[1]}]" if c else "—"


def _ev(x):
    return x.replace("|", " ") if x else "—"


def _link_line(lk):
    st = lk.get("status")
    if st in ("T7_10", "T1_6", "T11_30", "T31_PLUS"):
        mid = (f" · earlier episode in between: {', '.join(_ev(e) for e in lk['earlier_episode_in_between'])}"
               if lk.get("earlier_episode_in_between") else "")
        x70 = lk["x70"] or "— (a jump that never closes +70%)"
        return (f"{st} · {lk['sessions_to_onset']} sessions to onset {lk['onset']} (+70% close {x70} · "
                f"D1 {lk['d1']}){mid}")
    if st == "IN_EVENT":
        nx = (f"; next clean onset {lk['next_clean_onset']} in {lk['sessions_to_next_clean_onset']} sessions"
              if lk.get("next_clean_onset") else "")
        return f"IN_EVENT inside {_ev(lk['episode'])} ({lk['quality']}){nx}"
    if st in ("NO_LATER_CLEAN_EPISODE", "CENSORED_LT10_SESSIONS_AFTER"):
        sp = lk.get("intraday_only_within_10") or []
        spx = (" · intraday-only threshold within 10 sessions: "
               + ", ".join(f"{z['session']} (high +{z['high_vs_prior_close_pct']}%, close {z['close_vs_prior_close_pct']:+}%)"
                           for z in sp)) if sp else ""
        return f"{st} ({lk['sessions_of_data_after']} sessions of data after){spx}"
    return st


